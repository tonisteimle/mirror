/**
 * Helper: emit an `execute` step that rewrites a single Mirror source
 * line in place. Used for region/container layout-prop updates that
 * the property-panel surface doesn't expose as plain inputs.
 */
function rewriteLine(opts: {
  matchPattern: string // RegExp source matching the target line (anchored ^)
  newLine: string
  comment: string
}): { action: 'execute'; comment: string; code: string } {
  return {
    action: 'execute',
    comment: opts.comment,
    code: `
      (() => {
        const e = window.editor;
        if (!e) throw new Error('no editor');
        const src = e.state.doc.toString();
        const re = new RegExp('${opts.matchPattern}', 'm');
        const m = src.match(re);
        if (!m) throw new Error('rewriteLine: no match for ${opts.matchPattern}');
        const startPos = m.index;
        const endPos = startPos + m[0].length;
        e.dispatch({ changes: { from: startPos, to: endPos, insert: ${JSON.stringify(opts.newLine)} } });
      })()
    `,
  }
}

