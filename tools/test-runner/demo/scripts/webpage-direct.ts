/**
 * Webpage Direct-Manipulation Demo (full marketing page)
 *
 * Counterpart to webpage-build.ts: builds the SAME marketing page —
 * grid + 4 regions + header brand/nav/CTA + code-pane sidebar +
 * hero content + cards + 4-col footer — but through Studio's
 * direct-manipulation surfaces wherever feasible:
 *
 *   • Grid-cell drag            → drawInGrid       (4 regions)
 *   • Components panel drag     → dropFromPalette  (every primitive)
 *   • Inline editing            → inlineEdit       (every text/button)
 *   • Color picker              → pickColor        (key colors)
 *   • Property panel            → setProperty      (sizes, fs, weight)
 *
 * What stays as `execute`:
 *
 *   • The canvas + Stage shell line (typed once at the start — Mirror
 *     needs an explicit `canvas` directive and Studio has no surface
 *     to set the device preset).
 *   • Region-line layout updates (small 1-line replacements that set
 *     `hor, ver-center, spread, pad …, bor-b 1, boc …` — Studio's
 *     property panel exposes these as toggles/composites that the test
 *     runner's setProperty doesn't drive cleanly).
 *   • The code-pane Sidebar (~150 syntax-coloured spans generated by an
 *     inline tokenizer — too dense to drop one-by-one).
 *
 * The narrative arc is therefore: "draw regions → drop content into
 * them → name the pieces inline → polish a few colours". A user
 * watching this should be able to follow how a Mirror page assembles
 * without ever seeing me type Mirror DSL.
 */

